function rank(products: Product[]): RankedProduct[] {
  const trends: (number | "new")[] = [2, "new", -1, 0, 3, -2, 1, "new"];
  return products.map((product, index) => ({
    ...product,
    rank: index + 1,
    trend: trends[index % trends.length],
  }));
}

